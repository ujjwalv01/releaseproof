import type { CheckReport } from "@releaseproof/core";

/** GitHub truncates issue bodies above this; keep a margin for our own framing. */
export const ISSUE_BODY_LIMIT = 60_000;

const HEADINGS = {
  "matches-source": "✅ MATCHES SOURCE",
  "differs-from-source": "🚨 DIFFERS FROM SOURCE",
  "could-not-verify": "⚠️ COULD NOT VERIFY",
} as const;

/**
 * A fence longer than any backtick run inside the text, so untrusted content (file paths,
 * patch lines) can never close the block and inject markdown or HTML.
 */
export function fenceFor(text: string): string {
  let longest = 0;
  for (const run of text.match(/`+/g) ?? []) {
    longest = Math.max(longest, run.length);
  }
  return "`".repeat(Math.max(3, longest + 1));
}

export function issueTitle(report: CheckReport): string {
  const { name, version } = report.package;
  return `releaseproof: ${name}@${version} ${HEADINGS[report.verdict.status].replace(/^\S+\s/, "")}`;
}

/**
 * Markdown for the job summary when the check itself could not run. The heading comes from
 * our own code; the error message (which may quote registry URLs or file paths) sits in a
 * code fence, the way `renderMarkdown` treats package text.
 */
export function renderToolErrorMarkdown(
  message: string,
  options: { runUrl?: string | undefined } = {},
): string {
  const body = `## ${HEADINGS["could-not-verify"]} — the check itself failed\n\n`;
  const footer = [
    options.runUrl ? `Workflow run: ${options.runUrl}` : "",
    'Generated by releaseproof. "Could not verify" is never "safe".',
  ]
    .filter((line) => line !== "")
    .join("\n");
  const fence = fenceFor(message);
  return `${body}${fence}text\n${message}\n${fence}\n\n${footer}\n`;
}

/**
 * Markdown for the job summary and the issue body. Everything that came from the package
 * or the build sits inside one code block.
 */
export function renderMarkdown(
  report: CheckReport,
  textReport: string,
  options: {
    maxChars?: number | undefined;
    runUrl?: string | undefined;
    reportPath?: string | undefined;
  } = {},
): string {
  const maxChars = options.maxChars ?? ISSUE_BODY_LIMIT;
  const { name, version } = report.package;
  let body = `## ${HEADINGS[report.verdict.status]} — ${name}@${version}\n\n`;
  body += `${report.verdict.summary}\n\n`;
  const counts = report.verdict.counts;
  const countText = (["critical", "high", "medium", "low", "info"] as const)
    .filter((severity) => counts[severity] > 0)
    .map((severity) => `${counts[severity]} ${severity}`)
    .join(", ");
  body += `Findings: ${report.verdict.findings.length === 0 ? "none" : countText}\n\n`;

  const footer = [
    options.runUrl ? `Workflow run: ${options.runUrl}` : "",
    options.reportPath
      ? `Full JSON report: \`${options.reportPath}\` in the run's workspace (upload it as an artifact to keep it).`
      : "",
    'Generated by releaseproof. "Could not verify" is never "safe".',
  ]
    .filter((line) => line !== "")
    .join("\n");

  const fence = fenceFor(textReport);
  const frame = `${fence}text\n`;
  const close = `\n${fence}\n\n${footer}\n`;
  const budget = maxChars - body.length - frame.length - close.length - 80;
  let text = textReport;
  if (text.length > budget) {
    text = `${text.slice(0, Math.max(0, budget))}\n… truncated; the JSON report has everything`;
  }
  return `${body}${frame}${text}${close}`;
}
