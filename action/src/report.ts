import { type CheckReport, type Finding, parseSpec, sortFindings } from "@releaseproof/core";

/** GitHub truncates issue bodies above this; keep a margin for our own framing. */
export const ISSUE_BODY_LIMIT = 60_000;

/**
 * The verdict summary is repeated in full inside the text report; above it, a long one
 * (for example a list of unreadable archive entries) is cut to this many characters.
 */
export const SUMMARY_LIMIT = 1_000;

/** Shown instead of a package name or version that is not well formed. */
const UNNAMED_PACKAGE = "(package name not shown: the registry returned a malformed one)";

/**
 * `name@version` when both are a valid npm name and an exact version, so it is safe outside
 * a code block. For a staged version they come from the registry's stage item, which is
 * untrusted data, so anything else is replaced by a fixed note.
 */
function packageLabel(report: CheckReport): string | undefined {
  const label = `${report.package.name}@${report.package.version}`;
  try {
    parseSpec(label);
    return label;
  } catch {
    return undefined;
  }
}

const HEADINGS = {
  "matches-source": "✅ MATCHES SOURCE",
  "differs-from-source": "🚨 DIFFERS FROM SOURCE",
  "could-not-verify": "⚠️ COULD NOT VERIFY",
} as const;

function findingBullets(findings: Finding[]): string[] {
  const groups = new Map<string, { severity: Finding["severity"]; count: number }>();
  for (const { id, severity } of sortFindings(findings)) {
    const group = groups.get(id);
    if (group) {
      group.count += 1;
    } else {
      // Sorted first: a repeated id keeps its most severe occurrence.
      groups.set(id, { severity, count: 1 });
    }
  }
  return [...groups].map(
    ([id, { severity, count }]) =>
      `- **${severity}** [\`${id}\`](https://github.com/ujjwalv01/releaseproof/blob/main/docs/rules.md)${count > 1 ? ` (${count})` : ""}\n`,
  );
}

/**
 * A fence longer than any backtick run inside the text, so untrusted content (file paths,
 * patch lines) can never close the block and inject markdown or HTML.
 */
export function fenceFor(text: string): string {
  let longest = 0;
  for (const run of text.match(/`+/g) ?? []) {
    longest = Math.max(longest, run.length);
  }
  return "`".repeat(Math.max(3, longest + 1));
}

export function issueTitle(report: CheckReport): string {
  const verdict = HEADINGS[report.verdict.status].replace(/^\S+\s/, "");
  return `releaseproof: ${packageLabel(report) ?? UNNAMED_PACKAGE} ${verdict}`;
}

/** The verdict summary in its own code block: it can quote archive paths and provenance text. */
function summaryBlock(summary: string): string {
  const text =
    summary.length > SUMMARY_LIMIT
      ? `${summary.slice(0, SUMMARY_LIMIT)}… (shortened; the full summary is in the report below)`
      : summary;
  const fence = fenceFor(text);
  return `${fence}text\n${text}\n${fence}\n\n`;
}

/**
 * Markdown for the job summary when the check itself could not run. The heading comes from
 * our own code; the error message (which may quote registry URLs or file paths) sits in a
 * code fence, the way `renderMarkdown` treats package text.
 */
export function renderToolErrorMarkdown(
  message: string,
  options: { runUrl?: string | undefined } = {},
): string {
  const body = `## ${HEADINGS["could-not-verify"]} — the check itself failed\n\n`;
  const footer = [
    options.runUrl ? `Workflow run: ${options.runUrl}` : "",
    'Generated by releaseproof. "Could not verify" is never "safe".',
  ]
    .filter((line) => line !== "")
    .join("\n");
  const fence = fenceFor(message);
  return `${body}${fence}text\n${message}\n${fence}\n\n${footer}\n`;
}

/**
 * Markdown for the job summary and the issue body. Everything that came from the package,
 * the registry or the build sits inside code blocks: the verdict summary in one, the text
 * report in another. Outside them there is only our own text, the finding ids (fixed
 * strings from the rules) and a package name that passed `parseSpec`.
 */
export function renderMarkdown(
  report: CheckReport,
  textReport: string,
  options: {
    maxChars?: number | undefined;
    runUrl?: string | undefined;
    reportPath?: string | undefined;
  } = {},
): string {
  const maxChars = options.maxChars ?? ISSUE_BODY_LIMIT;
  const label = packageLabel(report);
  let body = `## ${HEADINGS[report.verdict.status]} — ${label ? `\`${label}\`` : UNNAMED_PACKAGE}\n\n`;
  body += summaryBlock(report.verdict.summary);
  const counts = report.verdict.counts;
  const countText = (["critical", "high", "medium", "low", "info"] as const)
    .filter((severity) => counts[severity] > 0)
    .map((severity) => `${counts[severity]} ${severity}`)
    .join(", ");
  body += `Findings: ${report.verdict.findings.length === 0 ? "none" : countText}\n\n`;

  const footer = [
    options.runUrl ? `Workflow run: ${options.runUrl}` : "",
    options.reportPath
      ? `Full JSON report: \`${options.reportPath}\` in the run's workspace (upload it as an artifact to keep it).`
      : "",
    'Generated by releaseproof. "Could not verify" is never "safe".',
  ]
    .filter((line) => line !== "")
    .join("\n");

  const fence = fenceFor(textReport);
  const frame = `${fence}text\n`;
  const close = `\n${fence}\n\n${footer}\n`;
  const list = findingBullets(report.verdict.findings);
  if (list.length > 0) {
    const available = maxChars - body.length - frame.length - close.length - 80;
    const fullList = `${list.join("")}\n`;
    if (fullList.length <= available) {
      body += fullList;
    } else {
      const notice = "… finding list truncated; the JSON report has everything\n\n";
      let used = notice.length;
      for (const bullet of list) {
        if (used + bullet.length > available) {
          break;
        }
        body += bullet;
        used += bullet.length;
      }
      if (used <= available) {
        body += notice;
      }
    }
  }
  const budget = maxChars - body.length - frame.length - close.length - 80;
  let text = textReport;
  if (text.length > budget) {
    text = `${text.slice(0, Math.max(0, budget))}\n… truncated; the JSON report has everything`;
  }
  return `${body}${frame}${text}${close}`;
}
